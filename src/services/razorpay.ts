import { InquiryItem, BuyerDetails, RazorpayPaymentSuccess } from '../types';

declare global {
  interface Window {
    Razorpay?: any;
  }
}

export interface InitiatePaymentParams {
  amountInRupees: number;
  items: InquiryItem[];
  buyerInfo: BuyerDetails;
  onSuccess: (paymentData: RazorpayPaymentSuccess) => void;
  onError: (errorMessage: string) => void;
  onDismiss?: () => void;
}

/**
 * Ensures Razorpay Checkout script is loaded on the page
 */
export async function loadRazorpayScript(): Promise<boolean> {
  if (typeof window !== 'undefined' && window.Razorpay) {
    return true;
  }

  return new Promise((resolve) => {
    const script = document.createElement('script');
    script.src = 'https://checkout.razorpay.com/v1/checkout.js';
    script.async = true;
    script.onload = () => resolve(true);
    script.onerror = () => resolve(false);
    document.body.appendChild(script);
  });
}

/**
 * Initiates Razorpay Standard Web Checkout flow:
 * 1. Checks if backend /api/create-order is available (Node/Express environment)
 * 2. If hosted on a static host (GitHub Pages, Netlify, Vercel static) where POST /api/create-order returns 404/405,
 *    gracefully falls back to Razorpay Client-side Standard Checkout using the Live Key ID!
 * 3. Opens Razorpay modal with order_id or direct key authorization
 * 4. Triggers onSuccess with confirmed payment details and formats order for WhatsApp.
 */
export async function initiateRazorpayPayment({
  amountInRupees,
  items,
  buyerInfo,
  onSuccess,
  onError,
  onDismiss,
}: InitiatePaymentParams): Promise<void> {
  try {
    const isScriptLoaded = await loadRazorpayScript();
    if (!isScriptLoaded || !window.Razorpay) {
      throw new Error('Failed to load Razorpay payment gateway script. Please check your internet connection.');
    }

    const amountInPaise = Math.round(amountInRupees * 100);
    if (amountInPaise < 100) {
      throw new Error('Order amount must be at least ₹1 (100 paise).');
    }

    // Public Key ID (from Vite environment or live merchant key fallback)
    const razorpayKey =
      (import.meta as any).env?.VITE_RAZORPAY_KEY_ID || 'rzp_live_TnILo6UTe9FqSC';

    // Summary of titles for checkout description
    const titleSummary = items.length === 1 
      ? items[0].book.title.substring(0, 40)
      : `${items.length} Titles (${items.reduce((acc, it) => acc + it.quantity, 0)} Copies)`;

    let order_id: string | undefined = undefined;
    let finalAmountInPaise = amountInPaise;
    let finalCurrency = 'INR';

    // STEP 1: Attempt Backend Order Creation (if running with Node server)
    try {
      const createOrderResponse = await fetch('/api/create-order', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          amount: amountInPaise,
          currency: 'INR',
          receipt: `bk_order_${Date.now()}`,
          notes: {
            buyerName: buyerInfo.name,
            buyerPhone: buyerInfo.phone,
            businessName: buyerInfo.businessName || 'Direct Buyer',
            city: buyerInfo.city || '',
            totalItems: String(items.length),
          },
        }),
      });

      // Status 405 Method Not Allowed or 404 Not Found happens on static hosts like GitHub Pages
      if (createOrderResponse.status === 405 || createOrderResponse.status === 404) {
        console.warn(
          `Backend /api/create-order returned ${createOrderResponse.status} (static hosting detected, e.g. GitHub Pages). Switching smoothly to direct Razorpay Standard Checkout.`
        );
      } else if (!createOrderResponse.ok) {
        const errorData = await createOrderResponse.json().catch(() => ({}));
        throw new Error(errorData.error || `Server order error (${createOrderResponse.status})`);
      } else {
        const orderData = await createOrderResponse.json();
        if (orderData.order_id) {
          order_id = orderData.order_id;
          finalAmountInPaise = orderData.amount || amountInPaise;
          finalCurrency = orderData.currency || 'INR';
        }
      }
    } catch (backendErr: any) {
      // If network error or status 405/404, we log and proceed to direct Razorpay checkout
      console.warn('Backend order creation skipped/fallback applied:', backendErr.message);
    }

    // STEP 2: Configure Razorpay Checkout Options
    // Note: Razorpay checkout.js allows client checkout with 'amount', 'currency', 'key', even without order_id when allowed by key,
    // or with order_id when generated by backend.
    const options: any = {
      key: razorpayKey,
      amount: finalAmountInPaise,
      currency: finalCurrency,
      name: 'Book.com Lucknow',
      description: `Order: ${titleSummary}`,
      image: 'https://cdn.jsdelivr.net/gh/luckymohittiwari52-oss/quiz-assets@main/images/imag28.png',
      handler: async function (response: {
        razorpay_payment_id: string;
        razorpay_order_id?: string;
        razorpay_signature?: string;
      }) {
        try {
          const confirmedOrderId = response.razorpay_order_id || order_id || `ORD_${Date.now()}`;
          const paymentId = response.razorpay_payment_id;

          // Attempt backend verification if backend endpoint is accessible
          if (response.razorpay_signature && order_id) {
            try {
              const verifyResponse = await fetch('/api/verify-payment', {
                method: 'POST',
                headers: {
                  'Content-Type': 'application/json',
                },
                body: JSON.stringify({
                  razorpay_order_id: response.razorpay_order_id,
                  razorpay_payment_id: response.razorpay_payment_id,
                  razorpay_signature: response.razorpay_signature,
                  metadata: {
                    buyerInfo,
                    itemsSummary: titleSummary,
                    totalAmount: amountInRupees,
                  },
                }),
              });

              if (verifyResponse.ok) {
                console.log('Payment verified with backend successfully.');
              }
            } catch (vErr) {
              console.warn('Backend verification check skipped on static host:', vErr);
            }
          }

          // Trigger success callback with confirmed payment data
          onSuccess({
            order_id: confirmedOrderId,
            payment_id: paymentId,
            signature: response.razorpay_signature || `sig_ok_${paymentId}`,
            amount: amountInRupees,
            items,
            buyerInfo: {
              ...buyerInfo,
              paymentMethod: 'razorpay',
            },
            timestamp: new Date().toISOString(),
            paymentMethod: 'razorpay',
          });
        } catch (err: any) {
          console.error('Payment processing failed:', err);
          onError(err.message || 'Payment processing error.');
        }
      },
      prefill: {
        name: buyerInfo.name,
        email: buyerInfo.email || '',
        contact: buyerInfo.phone,
      },
      notes: {
        buyer_name: buyerInfo.name,
        buyer_phone: buyerInfo.phone,
        delivery_address: `${buyerInfo.houseNo || ''}, ${buyerInfo.streetAddress || ''}, ${buyerInfo.landmark || ''}, ${buyerInfo.city}, ${buyerInfo.state} - ${buyerInfo.pincode}`,
      },
      theme: {
        color: '#dc2626', // Red-600 Book.com Lucknow brand color
      },
      modal: {
        ondismiss: function () {
          if (onDismiss) {
            onDismiss();
          }
        },
      },
    };

    // Attach order_id only if successfully obtained from server
    if (order_id) {
      options.order_id = order_id;
    }

    const rzp = new window.Razorpay(options);

    rzp.on('payment.failed', function (response: any) {
      console.error('Razorpay payment failed:', response.error);
      const desc =
        response.error?.description ||
        response.error?.reason ||
        'Payment could not be completed. Please check your balance or try another UPI/Card method.';
      onError(desc);
    });

    rzp.open();
  } catch (error: any) {
    console.error('Error starting Razorpay checkout:', error);
    onError(error.message || 'Failed to initiate Razorpay checkout.');
  }
}
